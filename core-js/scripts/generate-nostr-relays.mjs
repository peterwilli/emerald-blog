import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "../..");
const rustClientPath = path.join(repoRoot, "src/app/client.rs");
const outputPath = path.join(scriptDir, "../src/generated/nostr-relays.js");

const source = await readFile(rustClientPath, "utf8");
const match = source.match(/pub\s+const\s+NOSTR_RELAYS\s*:\s*&\s*\[\s*&str\s*\]\s*=\s*&\s*\[([\s\S]*?)\]\s*;/);

if (!match) {
  throw new Error(`Could not find pub const NOSTR_RELAYS in ${rustClientPath}`);
}

const relays = [...match[1].matchAll(/"((?:\\.|[^"\\])*)"/g)].map(([, relay]) =>
  JSON.parse(`"${relay}"`),
);

if (relays.length === 0) {
  throw new Error("NOSTR_RELAYS must contain at least one relay URL.");
}

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by core-js/scripts/generate-nostr-relays.mjs from src/app/client.rs.\n` +
    `export const DEFAULT_RELAYS = ${JSON.stringify(relays, null, 2)};\n`,
);
